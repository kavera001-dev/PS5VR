#!/usr/bin/env python3
"""Emit C tables of {name, offset} for chosen exports of decrypted system
libraries, for apps that cannot sceKernelDlsym them, plus one anchor string per
library (its address and text in the read-only data segment).

System library code is mapped execute-only, so the app checks the anchor string
instead: the offsets are used only if the string sits at the same offset, i.e.
it is the same library build, so other firmware fails safely.

usage: gen_export_table.py --fw <tag> [--optional <name>,...]
                           <lib.sprx> <name>... [-- <lib.sprx> <name>...] > table.h

<tag> is the firmware, e.g. 1360 for 13.60: it suffixes the table names, so
the tables of several firmware can sit side by side (app/src/vr_exports.h).
An --optional name that the library does not export is left out of the table
(the app runs without it); any other missing name is an error.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import ps5_dynlib  # noqa: E402


def anchor(prx):
    """First printable C string of 12+ chars in the read-only LOAD segment."""
    import re
    seg = next(p for p in prx.loads if p["flags"] == 4)
    data = prx.data[seg["offset"]:seg["offset"] + seg["filesz"]]
    m = re.search(rb"[A-Za-z][A-Za-z0-9 _%:.,()-]{11,59}\x00", data)
    text = m.group(0)[:-1].decode().replace("\\", "\\\\").replace('"', '\\"')
    return seg["vaddr"] + m.start(), text


def main():
    args = sys.argv[1:]
    if len(args) < 2 or args[0] != "--fw":
        sys.exit(__doc__)
    fw, args = args[1], args[2:]
    optional = set()
    if args[:1] == ["--optional"]:
        optional, args = set(args[1].split(",")), args[2:]
    groups, cur = [], []
    for arg in args:
        if arg == "--":
            groups.append(cur)
            cur = []
        else:
            cur.append(arg)
    groups.append(cur)

    names = ps5_dynlib.NameDB()
    names.load_persistent()
    # A NID is the hash of its name, so the wanted names resolve themselves
    # without tools/names.txt.
    for group in groups:
        for name in group[1:]:
            names.add(name)
    print("/* Generated by ps5vr/tools/gen_export_table.py - do not edit. */")
    for group in groups:
        lib, wanted = Path(group[0]), group[1:]
        prx = ps5_dynlib.Prx(lib)
        prx.resolve(names)
        by_name = {s["name"]: s for s in prx.exports() if s["name"]}
        stem = lib.name.split(".")[0]
        print(f"static const export_sig_t k{stem}Exports_{fw}[] = {{")
        for name in wanted:
            s = by_name.get(name)
            if s is None and name in optional:
                print(f"  /* {name}: not in this firmware */")
                print(f"{lib.name}: no {name} (optional)", file=sys.stderr)
                continue
            if s is None:
                sys.exit(f"{lib.name}: no export named {name}")
            print(f'  {{"{name}", 0x{s["value"]:x}}},')
        print("};")
        va, text = anchor(prx)
        print(f'static const export_anchor_t k{stem}Anchor_{fw} = {{0x{va:x}, "{text}"}};')


if __name__ == "__main__":
    main()
